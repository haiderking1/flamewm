#!/usr/bin/env python3
# src/xserver/fixed.c from misc-fixed's 6x13.bdf (public domain, xorg's
# font/misc-misc): the iso8859-1 cell font Xorg has built in as "fixed".
# 1-31 get the DEC line drawing glyphs xterm draws boxes with, like the
# misc-fixed iso8859-1 fonts have them
#   tools/fonts/bdf2c.py 6x13.bdf > src/xserver/fixed.c
import sys

DEC = [0x25C6, 0x2592, 0x2409, 0x240C, 0x240D, 0x240A, 0x00B0, 0x00B1, 0x2424, 0x240B,
       0x2518, 0x2510, 0x250C, 0x2514, 0x253C, 0x23BA, 0x23BB, 0x2500, 0x23BC, 0x23BD,
       0x251C, 0x2524, 0x2534, 0x252C, 0x2502, 0x2264, 0x2265, 0x03C0, 0x2260, 0x00A3,
       0x00B7]

glyphs = {}
code = None
rows = None
for line in open(sys.argv[1]):
    word = line.split()
    if not word:
        continue
    if word[0] == 'ENCODING':
        code = int(word[1])
    elif word[0] == 'BBX' and word[1:] != ['6', '13', '0', '-2']:
        sys.exit(f'glyph {code} is not a 6x13 cell')
    elif word[0] == 'BITMAP':
        rows = []
    elif word[0] == 'ENDCHAR':
        glyphs[code] = rows
        rows = None
    elif rows is not None:
        rows.append(int(word[0], 16))

table = {}
for c in range(256):
    ucs = DEC[c - 1] if 1 <= c <= 31 else c
    if 0x7f <= c <= 0x9f or ucs not in glyphs:
        continue  # not in iso8859-1: missing, the default char draws
    table[c] = glyphs[ucs]

print('// generated by tools/fonts/bdf2c.py from misc-fixed 6x13.bdf, public domain')
print('// ("Public domain font. Share and enjoy."). Xorg\'s built-in "fixed"\n')
print('#include "xserver/internal.h"\n')
print('const uint8_t xs_fixed_glyphs[256][XS_FIXED_HEIGHT] = {')
for c in sorted(table):
    print(f'\t[{c:#04x}] = {{' + ', '.join(f'{r:#04x}' for r in table[c]) + '},')
print('};\n')
present = [0] * 8
for c in table:
    present[c // 32] |= 1 << (c % 32)
print('const uint32_t xs_fixed_present[8] = {')
print('\t' + ', '.join(f'{w:#010x}' for w in present) + ',')
print('};')
